"use client";

import Link from "next/link";
import { useRouter } from "next/navigation";
import React, { FormEvent, useEffect, useRef, useState } from "react";
import { useAuth } from "../../../lib/auth";
import { writingReviewApi, type WritingReviewSummary } from "./review-api";
import {
  writingFoundationApi,
  eligibleWritingRubrics,
  type HumanWritingOptions,
} from "./foundation-api";
import { GovernanceError } from "./governance-ui";
import { AIWritingExecutionPanel } from "./execution-panel";
import css from "../assessment.module.css";

export default function WritingReviewQueuePage() {
  const { organisationId, permissions } = useAuth();
  const router = useRouter();
  const [reviews, setReviews] = useState<WritingReviewSummary[] | null>(null);
  const [options, setOptions] = useState<HumanWritingOptions | null>(null);
  const [sourceId, setSourceId] = useState("");
  const [rubricId, setRubricId] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [reload, setReload] = useState(0);
  const [busy, setBusy] = useState(false);
  const operations = useRef<Record<string, string>>({});
  const allowed = permissions.includes("subjective.read");
  const canInitialize = allowed && permissions.includes("subjective.assess");
  useEffect(() => {
    let cancelled = false;
    setReviews(null);
    setOptions(null);
    setError(null);
    setSourceId("");
    setRubricId("");
    if (!organisationId || !allowed) return;
    void Promise.all([
      writingReviewApi.list(organisationId),
      canInitialize
        ? writingFoundationApi.options(organisationId)
        : Promise.resolve(null),
    ])
      .then(([items, available]) => {
        if (!cancelled) {
          setReviews(items.filter((item) => item.skill === "WRITING"));
          setOptions(available);
        }
      })
      .catch((cause: unknown) => {
        if (!cancelled)
          setError(
            cause instanceof Error
              ? cause.message
              : "Writing review data could not be loaded.",
          );
      });
    return () => {
      cancelled = true;
    };
  }, [organisationId, allowed, canInitialize, reload]);
  const source = options?.submissions.find(
    (item) => item.candidate_response_revision_id === sourceId,
  );
  const rubrics = eligibleWritingRubrics(source, options?.rubrics ?? []);
  const rubric = rubrics.find((item) => item.id === rubricId);
  async function initialize(event: FormEvent) {
    event.preventDefault();
    if (!organisationId || !source || !rubric || !canInitialize || busy) return;
    setBusy(true);
    setError(null);
    const key = `${source.candidate_response_revision_id}:${rubric.id}:${rubric.checksum}`;
    const operation = (operations.current[key] ??= crypto.randomUUID());
    try {
      const assessment = await writingFoundationApi.initialize(
        organisationId,
        source,
        rubric,
        operation,
      );
      router.push(`/institution/writing-reviews/${assessment.id}`);
    } catch (cause) {
      setError(
        cause instanceof Error
          ? cause.message
          : "Human assessment initialization could not be confirmed. Refresh before retrying.",
      );
    } finally {
      setBusy(false);
    }
  }
  return (
    <section style={{ overflowWrap: "anywhere" }}>
      <h1>Writing review queue</h1>
      <p>
        Review exact submitted Writing evidence using a published rubric. Human
        assessments are recorded as HUMAN; no AI proposal is generated by this
        workflow.
      </p>
      {permissions.includes("rubric.read") && (
        <p>
          <Link href="/institution/rubrics">
            Inspect and publish Writing rubrics →
          </Link>
        </p>
      )}
      {!allowed || !organisationId ? (
        <p role="alert">
          Subjective read permission in an active institution is required.
        </p>
      ) : (
        <>
          <AIWritingExecutionPanel />
          {error && (
            <GovernanceError
              error={error}
              retry={() => setReload((value) => value + 1)}
            />
          )}
          {!reviews && !error && (
            <p role="status">Loading Writing review queue…</p>
          )}
          {options && (
            <section className={css.card}>
              <h2>Initialize human Writing assessment</h2>
              {!options.submissions.length ? (
                <p>
                  No eligible submitted Writing response is available for
                  initialization.
                </p>
              ) : (
                <form
                  className={css.form}
                  onSubmit={(event) => void initialize(event)}
                >
                  <label>
                    Submitted Writing response
                    <select
                      required
                      value={sourceId}
                      disabled={busy}
                      onChange={(event) => {
                        setSourceId(event.target.value);
                        setRubricId("");
                      }}
                    >
                      <option value="">
                        Select an exact submitted response
                      </option>
                      {options.submissions.map((item) => (
                        <option
                          key={item.candidate_response_revision_id}
                          value={item.candidate_response_revision_id}
                        >
                          {item.task_label} · response{" "}
                          {item.candidate_response_revision_id}
                        </option>
                      ))}
                    </select>
                  </label>
                  <label>
                    Published Writing rubric
                    <select
                      required
                      value={rubricId}
                      disabled={busy || !source}
                      onChange={(event) => setRubricId(event.target.value)}
                    >
                      <option value="">
                        Select a compatible published rubric
                      </option>
                      {rubrics.map((item) => (
                        <option key={item.id} value={item.id}>
                          {item.name} · {item.version_label ?? item.id}
                        </option>
                      ))}
                    </select>
                  </label>
                  {source && !rubrics.length && (
                    <p>
                      No published rubric matches this exact Standard Pack and
                      task specification. Publish the appropriate rubric before
                      starting human assessment.
                    </p>
                  )}
                  {source && rubric && (
                    <p className={css.notice}>
                      Source revision: {source.candidate_response_revision_id}.
                      Rubric: {rubric.id}. Origin will be HUMAN. An independent
                      authorised reviewer must decide the submitted assessment.
                    </p>
                  )}
                  <button disabled={busy || !source || !rubric}>
                    {busy
                      ? "Initializing human assessment…"
                      : "Initialize human Writing assessment"}
                  </button>
                </form>
              )}
            </section>
          )}
          {reviews && !reviews.length && (
            <p>
              No Writing assessment has been initialized in this institution.
            </p>
          )}
          {reviews?.map((review) => (
            <article className={css.card} key={review.id}>
              <h2>Writing assessment</h2>
              <p>
                Origin: {review.assessment_origin ?? "UNSPECIFIED"} · Status:{" "}
                {review.status}
              </p>
              <p>Attempt: {review.attempt_id}</p>
              <Link href={`/institution/writing-reviews/${review.id}`}>
                Inspect Writing assessment {review.id}
              </Link>
            </article>
          ))}
        </>
      )}
    </section>
  );
}
